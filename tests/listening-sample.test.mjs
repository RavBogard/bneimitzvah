import { test } from "node:test";
import assert from "node:assert/strict";
import { NAMED, DRAW_SIZE, listeningCandidates, renderSampleModule, selectListeningSample } from "../scripts/listening-sample.mjs";

// Synthetic index only: citations and numbers, no audio or text.
function synthetic() {
  const refs = [...NAMED.map(([ref]) => ref), ...Array.from({ length: 60 }, (_, i) => `Genesis 2:${i + 1}`), ...Array.from({ length: 40 }, (_, i) => `Isaiah 1:${i + 1}`)];
  const haftarah = ref => /^(Joshua|Judges|I |II |Isaiah|Jeremiah|Ezekiel|Hosea|Joel|Amos|Obadiah|Micah|Zechariah|Malachi)/.test(ref);
  const verses = refs.map((ref, i) => {
    const start = i * 10 + 1, words = 3 + (i % 9), step = 0.05 + (i % 7) * 0.1;
    return { ref, table: haftarah(ref) ? "haftarah" : "torah", playback: { status: "ready", asset: "ra_a", clip: { start, end: start + words * step + 0.2 + (i % 5) * 0.3 } },
      words: { status: "ready", starts: Array.from({ length: words }, (_, w) => start + 0.08 + w * step) } };
  });
  // Excluded: a duplicated reference, a held cut, a verse without word timing, and a verse with no published clip.
  verses.push({ ...verses[20], playback: { ...verses[20].playback } }); // duplicate of Genesis 2:7
  verses[30] = { ...verses[30], playback: { status: "needs-review", asset: "ra_a", clip: verses[30].playback.clip } };
  verses[31] = { ...verses[31], words: { status: "unavailable" } };
  const catalog = { schema: "reference-catalog/v1", assets: [{ id: "ra_a", verses }] };
  const entries = verses.filter((_, i) => i !== 32).filter(v => v.playback.status === "ready").map(v => {
    const first = Math.floor(v.playback.clip.start * 44100);
    return { parent: { asset: "ra_a" }, sampleRate: 44100, origin: { firstFrame: first }, presentationFrames: Math.ceil(v.playback.clip.end * 44100) - first };
  });
  return { catalog, manifest: { schema: "reference-short-manifest/v1", entries }, refs: verses.map(v => v.ref) };
}

test("candidates are exactly the published, single-recording, word-timed, ready verses", () => {
  const { catalog, manifest, refs } = synthetic(), candidates = listeningCandidates(catalog, manifest).map(c => c.ref);
  for (const index of [20, 30, 31, 32]) assert.ok(!candidates.includes(refs[index]), refs[index]);
  assert.equal(candidates.length, refs.length - 1 /* duplicate row */ - 4);
});

test("the stress set and seeded draw are deterministic, disjoint and carry only citations", () => {
  const { catalog, manifest } = synthetic();
  const one = selectListeningSample(catalog, manifest), two = selectListeningSample(catalog, manifest);
  assert.deepEqual(one, two);
  for (const [ref] of NAMED) assert.ok(one.stress.some(row => row.ref === ref), ref);
  assert.equal(one.draw.length, DRAW_SIZE);
  const stress = new Set(one.stress.map(row => row.ref));
  assert.ok(one.draw.every(row => !stress.has(row.ref)));
  assert.equal(new Set(one.draw.map(row => row.ref)).size, DRAW_SIZE);
  assert.ok([...one.stress, ...one.draw].every(row => Object.keys(row).every(key => ["kind", "ref", "why"].includes(key))));
  assert.notDeepEqual(selectListeningSample(catalog, manifest, { seed: "another seed" }).draw, one.draw);
  const module = renderSampleModule(one, { catalogSha256: "a".repeat(64), manifestSha256: "b".repeat(64) });
  assert.match(module, /^\/\/ Generated by scripts\/listening-sample\.mjs/);
  assert.ok(!/"?(starts|clip|playback|asset|words)"?\s*:/.test(module));
});

test("a named verse that is not playable stops regeneration instead of silently dropping it", () => {
  const { catalog, manifest } = synthetic();
  catalog.assets[0].verses = catalog.assets[0].verses.filter(v => v.ref !== NAMED[0][0]);
  assert.throws(() => selectListeningSample(catalog, manifest), /named verse/);
});
